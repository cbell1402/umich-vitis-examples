const float threshold = 0.5f;

void moduleCluster2d(data_t energy[NUM_CELLS], int labels[NUM_CELLS], int &numClusters) {

#pragma HLS ARRAY_PARTITION variable=labels complete

    bool active[NUM_CELLS];
#pragma HLS ARRAY_PARTITION variable=active complete

    for (int i=0; i<NUM_CELLS; i++) {
#pragma HLS PIPELINE II=1
        active[i] = (energy[i] > threshold);
        labels[i] = -1;
    }

    int queue[NUM_CELLS];
#pragma HLS ARRAY_PARTITION variable=queue complete

    numClusters = 0;

    for (int seed=0; seed<NUM_CELLS; seed++) {
        if (!active[seed])
            continue;
        
        if (labels[seed] != -1)
            continue;

        int front = 0;
        int back  = 0;

        queue[back++] = seed;

        labels[seed] = numClusters;

        while (front != back) {
            int current = queue[front++];

            for (int n=0; n<NUM_CELLS; n++) {
#pragma HLS PIPELINE II=1

                if (!neighbor[current][n])
                    continue;

                if (!active[n])
                    continue;
                
                if (labels[n] != -1)
                    continue;
                
                labels[n] = numClusters;

                queue[back++] = n;
            }
        }
        numClusters++;
    }
}